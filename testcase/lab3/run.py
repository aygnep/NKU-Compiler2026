#!/usr/bin/env python3
"""Lab3 regression and unmodified official LLVM tests. Run from repository root.

python3 testcase/lab3/run.py --official --native --logs /tmp/lab3-results
--native rebuilds the runtime for the host CPU. It leaves tracked archives intact.
LLVM 14 requires the opt-in opaque-pointer switches; wrappers only add those and
an earlier native library search path. Official test.py and expected files stay
unchanged. The two official groups must run serially (they share tmp.o/tmp.bin).
"""
import argparse
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]

